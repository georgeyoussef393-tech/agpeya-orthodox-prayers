    fun getArabicPsalm(number: Int): String? = verifiedArabicPsalms[number]

    fun requireArabicPsalm(number: Int): String =
        verifiedArabicPsalms[number]
            ?: error("Verified Arabic Psalm $number not yet registered in AgpeyaPsalmsRegistry")

    fun formatArabicPsalmWithHeader(number: Int): String {
        val body = requireArabicPsalm(number)
        return "(المزمور ${toArabicDigits(number)})\n$body"
    }

    fun toArabicDigits(number: Int): String {
        val arabicDigits = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')
        return number.toString().map { ch ->
            if (ch in '0'..'9') arabicDigits[ch - '0'] else ch
        }.joinToString("")
    }
